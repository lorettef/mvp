    render(<BudgetTab budgets={[plan,fact]} {...props} />)
    fireEvent.doubleClick(cell('ФОТ','Факт'))
    const input = desktop().getByRole('spinbutton')
    fireEvent.change(input,{ target:{ value:'0' } })
