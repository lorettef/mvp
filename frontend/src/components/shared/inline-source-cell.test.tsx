import { act, fireEvent, render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it, vi } from 'vitest'
import { InlineSourceCell } from './inline-source-cell'

function setup(overrides: Partial<React.ComponentProps<typeof InlineSourceCell>> = {}) {
  const save = vi.fn().mockResolvedValue(undefined)
  const props = { value: '100', label: 'Revenue Fact', children: '₽100', validate: (raw: string) => raw.trim() ? undefined : 'Required', onSave: save, ...overrides }
  const view = render(<InlineSourceCell {...props} />)
  return { ...view, save, props }
}
const begin = () => { fireEvent.doubleClick(screen.getByRole('button', { name: 'Revenue Fact' })); return screen.getByRole('spinbutton') }

describe('InlineSourceCell interaction', () => {
  it('shows the formatted server value, double-click edits raw value and selects it', () => {
    setup()
    expect(screen.getByRole('button')).toHaveTextContent('₽100')
    const input = begin()
    expect(input).toHaveValue(100)
    expect(input).toHaveFocus()
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  })
  it('starts with keyboard Enter, saves with Enter and restores focus without displaying the draft', async () => {
    const { save, rerender, props } = setup()
    const user = userEvent.setup()
    act(() => screen.getByRole('button').focus())
    await user.keyboard('{Enter}')
    const input = screen.getByRole('spinbutton')
    fireEvent.change(input, { target: { value: '200' } })
    await user.keyboard('{Enter}')
    expect(save).toHaveBeenCalledOnce()
    expect(save).toHaveBeenCalledWith('200')
    expect(screen.getByRole('button')).toHaveFocus()
    expect(screen.getByRole('button')).toHaveTextContent('₽100')
    rerender(<InlineSourceCell {...props} value="201" children="₽201" />)
    expect(screen.getByRole('button')).toHaveTextContent('₽201')
  })
  it('Tab/blur commits exactly once', async () => {
    const { save } = setup()
    const input = begin()
    fireEvent.change(input, { target: { value: '200' } })
    await userEvent.setup().tab()
    await waitFor(() => expect(screen.queryByRole('spinbutton')).not.toBeInTheDocument())
    expect(save).toHaveBeenCalledOnce()
  })
  it('guards Enter plus its resulting blur and repeated Enter while pending', async () => {
    let finish!: () => void
    const save = vi.fn().mockImplementation(() => new Promise<void>((r) => { finish = r }))
    setup({ onSave: save })
    const input = begin()
    fireEvent.change(input, { target: { value: '200' } })
    fireEvent.keyDown(input, { key: 'Enter' })
    fireEvent.blur(input)
    fireEvent.keyDown(input, { key: 'Enter' })
    expect(input).toHaveAttribute('readonly')
    expect(screen.getByRole('status')).toHaveTextContent('Сохранение')
    expect(save).toHaveBeenCalledOnce()
    await act(async () => finish())
    expect(screen.getByRole('button')).toHaveFocus()
  })
  it('Escape cancels even if blur follows; no request and focus returns to cell', () => {
    const { save } = setup()
    const input = begin()
    fireEvent.change(input, { target: { value: '200' } })
    fireEvent.keyDown(input, { key: 'Escape' })
    fireEvent.blur(input)
    expect(save).not.toHaveBeenCalled()
    expect(screen.getByRole('button')).toHaveTextContent('₽100')
    expect(screen.getByRole('button')).toHaveFocus()
  })
  it.each(['Enter', 'blur'])('exits unchanged on %s without a request', (event) => {
    const { save } = setup()
    const input = begin()
    if (event === 'Enter') fireEvent.keyDown(input, { key: event })
    else fireEvent.blur(input)
    expect(save).not.toHaveBeenCalled()
    expect(screen.queryByRole('spinbutton')).not.toBeInTheDocument()
  })
  it('rejects an empty required value without treating it as zero', () => {
    const { save } = setup()
    const input = begin()
    fireEvent.change(input, { target: { value: '' } })
    fireEvent.blur(input)
    expect(save).not.toHaveBeenCalled()
    expect(input).toHaveAttribute('aria-invalid', 'true')
    expect(input).toHaveFocus()
    expect(input).toHaveAccessibleDescription('Required')
  })
  it('keeps normalized API error and draft, suppresses blur retries and permits explicit retry', async () => {
    const save = vi.fn().mockRejectedValueOnce({ response: { data: { detail: 'Offline' } } }).mockResolvedValue(undefined)
    setup({ onSave: save })
    const input = begin()
    fireEvent.change(input, { target: { value: '200' } })
    fireEvent.keyDown(input, { key: 'Enter' })
    expect(await screen.findByRole('alert')).toHaveTextContent('Offline')
    expect(input).toHaveValue(200)
    expect(input).toHaveFocus()
    fireEvent.blur(input)
    fireEvent.blur(input)
    expect(save).toHaveBeenCalledOnce()
    fireEvent.keyDown(input, { key: 'Enter' })
    await waitFor(() => expect(screen.queryByRole('spinbutton')).not.toBeInTheDocument())
    expect(save).toHaveBeenCalledTimes(2)
  })
  it('allows correcting an error then saving on blur, and Escape after another error', async () => {
    const save = vi.fn().mockRejectedValue(new Error('Offline'))
    setup({ onSave: save })
    const input = begin()
    fireEvent.change(input, { target: { value: '200' } })
    fireEvent.blur(input)
    await screen.findByRole('alert')
    fireEvent.change(input, { target: { value: '300' } })
    fireEvent.blur(input)
    await waitFor(() => expect(save).toHaveBeenCalledTimes(2))
    await waitFor(() => expect(input).not.toHaveAttribute('readonly'))
    fireEvent.keyDown(input, { key: 'Escape' })
    expect(screen.getByRole('button')).toHaveTextContent('₽100')
  })
  it('does not start editing a busy source', () => {
    const { save } = setup({ busy: true })
    fireEvent.doubleClick(screen.getByRole('button'))
    fireEvent.keyDown(screen.getByRole('button'), { key: 'Enter' })
    expect(screen.queryByRole('spinbutton')).not.toBeInTheDocument()
    expect(save).not.toHaveBeenCalled()
  })
})
